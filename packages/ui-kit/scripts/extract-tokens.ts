import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Reads the design reference's `:root` custom properties and writes every token artefact in the
// repo from them. Nothing downstream may type a colour, a spacing step or a shadow by hand: the
// HTML is the design system, and `test/tokens.test.ts` re-parses it to prove these files still agree.

/** The reference's file name, so tests can resolve it from their own location. */
export const REFERENCE_FILE = 'Komtru — UI Screens Living Master File.html';

/** The reference HTML, resolved from this package rather than the caller's working directory. */
export const REFERENCE_HTML = new URL(`../../../docs/design-reference/${REFERENCE_FILE}`, import.meta.url);

/** The number of custom properties the reference declares. The ticket's count, confirmed. */
export const TOKEN_COUNT = 52;

/**
 * Splits a declaration list on `;`, ignoring semicolons nested in parentheses or quotes. A naive
 * `split(';')` happens to work today but would cut `--shadow-card` in half the moment someone adds
 * a value containing one, which is exactly the silent corruption this file exists to prevent.
 */
function splitDeclarations(body: string): string[] {
  // Comments first: `/* note; here */` would otherwise parse as a declaration named `/* note`.
  const text = body.replace(/\/\*[\s\S]*?\*\//g, '');
  const parts: string[] = [];
  let depth = 0;
  let quote: string | null = null;
  let start = 0;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quote !== null) {
      if (char === quote) quote = null;
      continue;
    }
    if (char === "'" || char === '"') quote = char;
    else if (char === '(') depth += 1;
    else if (char === ')') depth -= 1;
    else if (char === ';' && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((part) => part.trim()).filter((part) => part.length > 0);
}

/**
 * Parses a `{ … }` body into name → value. Throws on a repeated name, which in a generated file
 * means the renderer emitted a token twice.
 */
export function parseCssDeclarations(body: string): Map<string, string> {
  const declarations = new Map<string, string>();
  for (const declaration of splitDeclarations(body)) {
    const colon = declaration.indexOf(':');
    if (colon === -1) throw new Error(`Declaration without a value: ${declaration}`);
    const name = declaration.slice(0, colon).trim();
    const value = declaration.slice(colon + 1).trim();
    if (declarations.has(name)) throw new Error(`Duplicate custom property ${name}`);
    declarations.set(name, value);
  }
  return declarations;
}

/** The body of every `:root { … }` rule inside a `<style>` element, in document order. */
export function rootBlocks(html: string): string[] {
  const bodies: string[] = [];
  for (const style of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)) {
    for (const block of (style[1] ?? '').matchAll(/:root\s*\{([^}]*)\}/g)) {
      bodies.push(block[1] ?? '');
    }
  }
  return bodies;
}

/**
 * The tokens all `:root` blocks agree on. The reference repeats the block once per section it was
 * assembled from, so a value edited in only one copy is the realistic way the design system drifts;
 * comparing the blocks catches that instead of silently preferring the first one.
 */
export function parseRootTokens(html: string): Map<string, string> {
  const blocks = rootBlocks(html);
  if (blocks.length === 0) throw new Error('The reference HTML declares no :root block');

  const [first, ...rest] = blocks;
  const tokens = parseCssDeclarations(first ?? '');

  for (const [index, block] of rest.entries()) {
    const other = parseCssDeclarations(block);
    for (const [name, value] of tokens) {
      const found = other.get(name);
      if (found === undefined) throw new Error(`:root block ${index + 2} is missing ${name}`);
      if (found !== value) {
        throw new Error(`:root block ${index + 2} sets ${name} to ${found}, not ${value}`);
      }
    }
    for (const name of other.keys()) {
      if (!tokens.has(name)) throw new Error(`:root block ${index + 2} adds ${name}`);
    }
  }

  return tokens;
}

const HEADER_LINES = [
  'Generated by packages/ui-kit/scripts/extract-tokens.ts from',
  `docs/design-reference/${REFERENCE_FILE}. Do not edit by hand.`,
];

/**
 * A TypeScript string literal in the repo's Prettier style: single quotes, unless the value itself
 * contains one (the font stacks do).
 */
function quote(value: string): string {
  return value.includes("'") ? JSON.stringify(value) : `'${value}'`;
}

/** The stylesheet every non-Tailwind consumer loads: Storybook, the visual-check harness, emails. */
export function renderTokensCss(tokens: Map<string, string>): string {
  return [
    '/*',
    ...HEADER_LINES.map((line) => ` * ${line}`),
    ' */',
    ':root {',
    ...[...tokens].map(([name, value]) => `  ${name}: ${value};`),
    '}',
    '',
  ].join('\n');
}

/** The same tokens for TypeScript, so a component can name a token instead of repeating its value. */
export function renderTokensTs(tokens: Map<string, string>): string {
  return [
    ...HEADER_LINES.map((line) => `// ${line}`),
    '',
    '/* eslint-disable komtru-design/no-raw-hex -- the generated palette is where the raw values belong. */',
    'export const KOMTRU_TOKENS = {',
    ...[...tokens].map(([name, value]) => `  '${name}': ${quote(value)},`),
    '} as const satisfies Record<string, string>;',
    '',
    "/** One of the reference HTML's custom property names. */",
    'export type KomtruTokenName = keyof typeof KOMTRU_TOKENS;',
    '',
    "/** `cssVar('--trust-emerald')` becomes `var(--trust-emerald)`, for SVG attributes and inline styles. */",
    'export const cssVar = (name: KomtruTokenName): string => `var(${name})`;',
    '',
  ].join('\n');
}

// Tailwind v4 reads its theme from custom properties in named namespaces. Six of the HTML's tokens
// already sit in one (`--font-*`, `--shadow-*`, `--ease-*`), so declaring them inside `@theme`
// publishes the property and creates the utility in one go. The rest need an alias, and the alias
// must not be declared twice: `--font-display: var(--font-display)` is self-referential and would
// make the property invalid at computed-value time, taking the whole font stack with it.
const NATIVE_NAMESPACES = ['--font-', '--shadow-', '--ease-'];

const isNative = (name: string) => NATIVE_NAMESPACES.some((prefix) => name.startsWith(prefix));

// Tailwind ships ~250 colours of its own. Left in place they sit beside the reference's palette and
// read exactly like it — `text-slate-700` next to the real `text-slate` — and no lint rule can tell
// them apart, because there is no hex involved. Retiring the namespace makes every colour utility a
// token by construction. The three keywords stay: the reference writes `transparent` and `#fff`
// through `--pure-white`, and `currentColor` is how an icon inherits its parent's colour.
const COLOUR_RESET = [
  '--color-*: initial;',
  '--color-transparent: transparent;',
  '--color-current: currentColor;',
  '--color-inherit: inherit;',
];

/** The Tailwind theme key a token maps to, or null when the token has no Tailwind namespace. */
function tailwindAlias(name: string): string | null {
  if (name.startsWith('--sp-')) return `--spacing-${name.slice('--sp-'.length)}`;
  if (name.startsWith('--r-')) return `--radius-${name.slice('--r-'.length)}`;
  // Durations are last: Tailwind v4 has no duration namespace, so `--dur-*` stays a plain property
  // consumed as `var(--dur-standard)`.
  if (name.startsWith('--dur-')) return null;
  return `--color-${name.slice('--'.length)}`;
}

/** The single stylesheet every app imports: Tailwind, the reference tokens, and the theme mapping. */
export function renderTailwindPreset(tokens: Map<string, string>): string {
  const native = [...tokens].filter(([name]) => isNative(name));
  const plain = [...tokens].filter(([name]) => !isNative(name));
  const aliases = plain
    .map(([name]) => [tailwindAlias(name), name] as const)
    .filter((pair): pair is readonly [string, string] => pair[0] !== null);

  return [
    '/*',
    ...HEADER_LINES.map((line) => ` * ${line}`),
    ' */',
    "@import 'tailwindcss';",
    '',
    '/* Tokens whose name is already a Tailwind namespace: font-display, shadow-card, ease-standard.',
    '   `static` because Tailwind otherwise drops a theme property no utility used, and the reference',
    '   reaches for these from plain CSS (`h1 { font-family: var(--font-display) }`). */',
    '@theme static {',
    ...native.map(([name, value]) => `  ${name}: ${value};`),
    '}',
    '',
    '/* The rest of the reference tokens, verbatim. */',
    ':root {',
    ...plain.map(([name, value]) => `  ${name}: ${value};`),
    '}',
    '',
    '/* `inline` keeps each utility pointing at the reference token rather than copying its value. */',
    '@theme inline {',
    ...COLOUR_RESET.map((line) => `  ${line}`),
    ...aliases.map(([alias, name]) => `  ${alias}: var(${name});`),
    '}',
    '',
  ].join('\n');
}

/** `pnpm --filter @komtru/ui-kit tokens` rewrites every artefact from the reference. */
export function writeArtefacts(): void {
  const tokens = parseRootTokens(readFileSync(REFERENCE_HTML, 'utf8'));
  if (tokens.size !== TOKEN_COUNT) {
    throw new Error(`The reference now declares ${tokens.size} tokens, not ${TOKEN_COUNT}`);
  }
  writeFileSync(new URL('../src/tokens.css', import.meta.url), renderTokensCss(tokens));
  writeFileSync(new URL('../src/tokens.ts', import.meta.url), renderTokensTs(tokens));
  writeFileSync(new URL('../../config/tailwind/preset.css', import.meta.url), renderTailwindPreset(tokens));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeArtefacts();
