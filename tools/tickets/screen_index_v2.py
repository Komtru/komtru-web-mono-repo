#!/usr/bin/env python3
"""Regenerate docs/design-reference/SCREEN_INDEX.md from the UI Living Master v2 inventory.

Inputs: docs/design-reference/screens-v2.tsv (line, section, heading, screen, status_vs_v1), the v2
HTML (for each screen's title) and tools/tickets/screen_map_v2.json, which holds the decisions:

    apps       ticket -> app that builds it
    sections   section name -> ticket (the default for every screen in the section)
    overrides  screen id -> ticket (wins over its section)

Bare numeric ids in the reference (1-10) are prefixed with the section: Customer-3, Seller-3.
Every screen must resolve to exactly one ticket that has an app; anything else fails the run.

    python3 tools/tickets/screen_index_v2.py            # write SCREEN_INDEX.md
    python3 tools/tickets/screen_index_v2.py --check    # fail if the file is stale
    python3 tools/tickets/screen_index_v2.py --tickets  # print ticket -> screen ids
"""

from __future__ import annotations

import csv
import html
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "docs" / "design-reference"
TSV = REF / "screens-v2.tsv"
HTML = REF / "Komtru — UI Living Master v2.html"
MAP = Path(__file__).with_name("screen_map_v2.json")
OUT = REF / "SCREEN_INDEX.md"

NUMERIC_PREFIX = {"Customer (Buyer) — Mobile Web": "Customer", "Seller — Mobile Web": "Seller"}

HEADER = """# Reference screen index (UI Living Master v2)

Generated by `tools/tickets/screen_index_v2.py` from `screens-v2.tsv`, the v2 HTML and `tools/tickets/screen_map_v2.json`; edit the map, not this file. The reference numbers the customer and seller tab screens 1–10; they are listed as `Customer-1`–`Customer-10` and `Seller-1`–`Seller-10`. "Line" is the line in `Komtru — UI Living Master v2.html` where the screen starts. The v1 index, kept for the visual checks of finished tickets, is `SCREEN_INDEX-v1.md`.

| ID | Screen | Reference section | Line | App | Ticket |
|---|---|---|---|---|---|
"""


def load_rows() -> list[dict]:
    lines = HTML.read_text().split("\n")
    rows = []
    with TSV.open() as fh:
        for rec in csv.DictReader(fh, delimiter="\t"):
            line = int(rec["line"])
            sid = rec["screen"].split(" ", 1)[0]
            if sid.isdigit():
                sid = f"{NUMERIC_PREFIX[rec['section']]}-{sid}"
            m = re.search(r'<div class="n">[^<]*</div><div><b>([^<]*)</b>', lines[line - 1])
            if not m:
                sys.exit(f"no screen-num header at line {line} for {sid}")
            rows.append({"id": sid, "title": html.unescape(m.group(1)).replace("|", "/"),
                         "section": rec["section"], "line": line})
    return rows


def build() -> tuple[str, dict[str, list[str]]]:
    cfg = json.loads(MAP.read_text())
    apps, sections, overrides = cfg["apps"], cfg["sections"], cfg["overrides"]
    rows = load_rows()
    seen: set[str] = set()
    by_ticket: dict[str, list[str]] = defaultdict(list)
    out = [HEADER]
    for r in rows:
        if r["id"] in seen:
            sys.exit(f"duplicate id {r['id']}")
        seen.add(r["id"])
        ticket = overrides.get(r["id"]) or sections.get(r["section"])
        if not ticket:
            sys.exit(f"unmapped: {r['id']} ({r['section']})")
        if ticket not in apps:
            sys.exit(f"{r['id']} -> {ticket} has no app in the map")
        by_ticket[ticket].append(r["id"])
        out.append(f"| {r['id']} | {r['title']} | {r['section']} | {r['line']} | {apps[ticket]} | {ticket} |\n")
    for sid in overrides:
        if sid not in seen:
            sys.exit(f"override for unknown id {sid}")
    for sec in sections:
        if not any(r["section"] == sec for r in rows):
            sys.exit(f"map names unknown section {sec}")
    return "".join(out), by_ticket


def main() -> None:
    text, by_ticket = build()
    if "--tickets" in sys.argv:
        for t in sorted(by_ticket):
            print(t, len(by_ticket[t]), ", ".join(by_ticket[t]))
        return
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("SCREEN_INDEX.md is stale; run tools/tickets/screen_index_v2.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(v) for v in by_ticket.values())} screens, {len(by_ticket)} tickets")


if __name__ == "__main__":
    main()
